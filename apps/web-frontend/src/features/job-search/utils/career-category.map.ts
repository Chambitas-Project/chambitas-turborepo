export function getCategoriesForCareer(careerName: string, careerArea: string): string[] {
  if (CAREER_AREA_MAP[careerName]) {
    return CAREER_AREA_MAP[careerName];
  }
  
  for (const [key, cats] of Object.entries(CAREER_AREA_MAP)) {
    if (careerName.toLowerCase().includes(key.toLowerCase()) || key.toLowerCase().includes(careerName.toLowerCase())) {
      return cats;
    }
  }

  if (AREA_CATEGORY_MAP[careerArea]) {
    return AREA_CATEGORY_MAP[careerArea];
  }

  return ["Software y Tecnología", "Gestión y Negocios"];
}
